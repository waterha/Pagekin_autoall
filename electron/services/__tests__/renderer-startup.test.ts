import { EventEmitter } from 'node:events'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { loadRendererWithRecovery } from '../renderer-startup'

function fixture() {
  const contents = Object.assign(new EventEmitter(), { isDestroyed: () => false })
  const window = Object.assign(new EventEmitter(), { isDestroyed: () => false, webContents: contents })
  const load = vi.fn<() => Promise<unknown>>().mockResolvedValue(undefined)
  const onFailure = vi.fn()
  const onRetry = vi.fn()
  const start = () => loadRendererWithRecovery(window, { load, onFailure, onRetry })
  const crash = () => contents.emit('render-process-gone', {}, { reason: 'crashed', exitCode: -2147483645 })
  return { contents, window, load, onFailure, onRetry, start, crash }
}

afterEach(() => { vi.useRealTimers() })

describe('renderer startup recovery', () => {
  it('retries a native crash after 250 ms and stops recovering once the retry loads', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.start()
    f.crash()
    await vi.advanceTimersByTimeAsync(249)
    expect(f.load).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(f.load).toHaveBeenCalledTimes(2)
    expect(f.onRetry).toHaveBeenCalledWith(expect.objectContaining({ reason: 'crashed', exitCode: -2147483645, attempts: 1 }), 1)
    f.contents.emit('did-finish-load')
    f.crash()
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledTimes(2)
    expect(f.onFailure).not.toHaveBeenCalled()
  })

  it('deduplicates a crash and rejection from the same load and ignores an old rejection after success', async () => {
    vi.useFakeTimers()
    const f = fixture()
    let rejectOld!: (reason: Error) => void
    f.load.mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectOld = reject }))
    f.start()
    f.crash()
    rejectOld(new Error('ERR_FAILED'))
    await vi.advanceTimersByTimeAsync(250)
    expect(f.load).toHaveBeenCalledTimes(2)
    f.contents.emit('did-finish-load')
    await vi.runAllTimersAsync()
    expect(f.onRetry).toHaveBeenCalledOnce()
    expect(f.onFailure).not.toHaveBeenCalled()
  })

  it('reports one terminal failure after two retries, retaining the final native reason and code', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.start()
    f.crash()
    f.crash()
    await vi.advanceTimersByTimeAsync(250)
    f.crash()
    await vi.advanceTimersByTimeAsync(999)
    expect(f.load).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(1)
    expect(f.load).toHaveBeenCalledTimes(3)
    f.crash()
    f.crash()
    await vi.runAllTimersAsync()
    expect(f.onFailure).toHaveBeenCalledExactlyOnceWith({ reason: 'crashed', exitCode: -2147483645, attempts: 3 })
    expect(f.load).toHaveBeenCalledTimes(3)
    expect(vi.getTimerCount()).toBe(0)
    expect(f.contents.eventNames()).toEqual([])
  })

  it('retries rejected loads without an unhandled rejection and shows the last error message', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.load.mockRejectedValue(new Error('ERR_FILE_NOT_FOUND'))
    f.start()
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledTimes(3)
    expect(f.onFailure).toHaveBeenCalledExactlyOnceWith({ reason: 'load-failed', message: 'Error: ERR_FILE_NOT_FOUND', attempts: 3 })
    expect(f.contents.eventNames()).toEqual([])
  })

  it.each(['destroyed', 'closed'] as const)('cancels a scheduled retry when the window is %s', async event => {
    vi.useFakeTimers()
    const f = fixture()
    f.start()
    f.crash()
    if (event === 'closed') f.window.emit(event)
    else f.contents.emit(event)
    expect(vi.getTimerCount()).toBe(0)
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledOnce()
    expect(f.onFailure).not.toHaveBeenCalled()
    expect(f.contents.eventNames()).toEqual([])
    expect(f.window.eventNames()).toEqual([])
  })

  it('ignores an aborted older navigation while the newer load is still awaiting finish', async () => {
    vi.useFakeTimers()
    const f = fixture()
    let rejectOld!: (reason: Error) => void
    f.load.mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectOld = reject }))
    f.start()
    f.crash()
    await vi.advanceTimersByTimeAsync(250)
    rejectOld(new Error('ERR_ABORTED (-3) loading old URL'))
    await Promise.resolve()
    expect(f.onFailure).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    expect(f.contents.listenerCount('did-finish-load')).toBe(1)
    f.contents.emit('did-finish-load')
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledTimes(2)
    expect(f.onRetry).toHaveBeenCalledOnce()
  })

  it('ignores rejection of an older load after a retry successfully finishes', async () => {
    vi.useFakeTimers()
    const f = fixture()
    let rejectOld!: (reason: Error) => void
    f.load.mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectOld = reject }))
    f.start()
    f.crash()
    await vi.advanceTimersByTimeAsync(250)
    f.contents.emit('did-finish-load')
    rejectOld(new Error('OLD_LOAD_FAILED'))
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledTimes(2)
    expect(f.onFailure).not.toHaveBeenCalled()
  })

  it('does not treat a resolved load promise as did-finish-load or cancel its crash retry', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.start()
    await Promise.resolve()
    f.crash()
    f.contents.emit('did-finish-load')
    await vi.advanceTimersByTimeAsync(250)
    expect(f.load).toHaveBeenCalledTimes(2)
    f.contents.emit('did-finish-load')
    expect(f.contents.eventNames()).toEqual([])
  })

  it('allows explicit disposal to cancel all recovery work', async () => {
    vi.useFakeTimers()
    const f = fixture()
    const dispose = f.start()
    f.crash()
    dispose()
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledOnce()
    expect(f.onFailure).not.toHaveBeenCalled()
    expect(f.contents.eventNames()).toEqual([])
    expect(f.window.eventNames()).toEqual([])
  })

  it('catches a synchronous load failure through the same bounded recovery path', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.load.mockImplementation(() => { throw new Error('SYNC_LOAD_FAILED') })
    expect(() => f.start()).not.toThrow()
    await vi.runAllTimersAsync()
    expect(f.onFailure).toHaveBeenCalledExactlyOnceWith({ reason: 'load-failed', message: 'Error: SYNC_LOAD_FAILED', attempts: 3 })
  })

  it('starts the initial load and retires the guard only when the first page finishes', async () => {
    vi.useFakeTimers()
    const f = fixture()
    f.start()
    expect(f.load).toHaveBeenCalledOnce()
    await Promise.resolve()
    expect(f.contents.listenerCount('render-process-gone')).toBe(1)
    f.contents.emit('did-finish-load')
    await vi.runAllTimersAsync()
    expect(f.load).toHaveBeenCalledOnce()
    expect(f.onFailure).not.toHaveBeenCalled()
    expect(f.contents.eventNames()).toEqual([])
    expect(f.window.eventNames()).toEqual([])
  })
})
